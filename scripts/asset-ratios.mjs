// Reads every SVG in public/assets and writes src/lib/asset-ratios.ts, so each
// lazily inlined asset can reserve its exact space before it streams in.
// Runs automatically before `dev` and `build` (see package.json).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = join(import.meta.dirname, '..', 'public', 'assets');
const out = join(import.meta.dirname, '..', 'src', 'lib', 'asset-ratios.ts');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : path.endsWith('.svg') ? [path] : [];
  });
}

const entries = walk(root)
  .map((file) => {
    const head = readFileSync(file, 'utf8').slice(0, 600);
    const m = head.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
    return m ? [relative(root, file).split(sep).join('/'), `${m[1]} / ${m[2]}`] : null;
  })
  .filter(Boolean)
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(
  out,
  `// Generated by scripts/asset-ratios.mjs. Do not edit by hand.\n` +
    `export const ASSET_RATIOS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`asset-ratios: ${entries.length} assets`);
